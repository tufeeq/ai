// ---------- small helpers ----------

function send(res, status, obj, headers = {}) {
  if (!res || res.headersSent || res.writableEnded) return;
  res.writeHead(status, { 'Content-Type': 'application/json; charset=utf-8', 'Cache-Control': 'no-store', ...headers });
  res.end(JSON.stringify(obj));
}

function sendErr(res, status, code, message, headers) {
  send(res, status, { error: { code, message } }, headers);
}

function isPlainObject(v) {
  return v !== null && typeof v === 'object' && !Array.isArray(v);
}

function toNum(v) {
  if (v === null || v === undefined || v === '' || typeof v === 'boolean') return null;
  const n = typeof v === 'number' ? v : Number(String(v).replace(/[,%\s]/g, ''));
  return Number.isFinite(n) ? Number(n.toFixed(4)) : null;
}

/** Short safe label for values that end up inside the prompt. */
function toLabel(v, max = 40) {
  if (typeof v !== 'string' && typeof v !== 'number') return null;
  const s = String(v).replace(/[^\p{L}\p{N}_ .:+\-/]/gu, ' ').replace(/\s+/g, ' ').trim().slice(0, max);
  return s || null;
}

/** Coerce any model value to a single-line string capped at `max` characters. */
export function cleanText(v, max = MAX_TEXT) {
  let s = '';
  if (typeof v === 'string') s = v;
  else if (typeof v === 'number' && Number.isFinite(v)) s = String(v);
  else if (Array.isArray(v)) s = v.filter((x) => typeof x === 'string' || typeof x === 'number').join(' · ');
  // eslint-disable-next-line no-control-regex
  s = s.replace(/[\u0000-\u001f\u007f]+/g, ' ').replace(/\s+/g, ' ').trim();
  if (s.length > max) s = s.slice(0, max - 1).trimEnd() + '…';
  return s;
}

function cleanList(v) {
  let arr = [];
  if (Array.isArray(v)) arr = v;
  else if (typeof v === 'string' && v.trim()) arr = v.split(/\n+|\s*[;؛]\s*/);
  const out = [];
  for (const item of arr) {
    const s = cleanText(isPlainObject(item) ? item.text ?? item.title ?? '' : item, MAX_LIST_ITEM);
    if (s && !out.includes(s)) out.push(s);
    if (out.length >= MAX_LIST) break;
  }
  return out;
}

function cleanConfidence(v) {
  let n = typeof v === 'number' ? v : parseFloat(String(v ?? '').replace(',', '.'));
  if (!Number.isFinite(n)) return 0;
  if (n > 0 && n < 1) n *= 100; // small models sometimes answer 0.7 for 70
  return Math.min(100, Math.max(0, Math.round(n)));
}

function cleanVerdict(v) {
  const s = typeof v === 'string' ? v.trim().toUpperCase().replace(/[\s-]+/g, '_') : '';
  return VERDICTS.includes(s) ? s : 'INSUFFICIENT_EVIDENCE';
}

function httpUrl(v) {
  if (typeof v !== 'string') return null;
  try {
    const u = new URL(v.trim());
    return u.protocol === 'https:' || u.protocol === 'http:' ? u.href : null;
  } catch {
    return null;
  }
}

function isoDay(v) {
  if (typeof v !== 'string' && typeof v !== 'number') return '';
  const d = new Date(v);
  return Number.isNaN(d.getTime()) ? '' : d.toISOString().slice(0, 10);
}

/**
 * Extract the first JSON object from model text, even when wrapped in prose or code fences.
 * Returns a plain object or null.
 */
export function extractJsonObject(text) {
  if (isPlainObject(text)) return text;
  if (typeof text !== 'string') return null;
  let from = 0;
  while (from < text.length) {
    const start = text.indexOf('{', from);
    if (start === -1) return null;
    let depth = 0;
    let inStr = false;
    let esc = false;
    let end = -1;
    for (let i = start; i < text.length; i++) {
      const ch = text[i];
      if (inStr) {
        if (esc) esc = false;
        else if (ch === '\\') esc = true;
        else if (ch === '"') inStr = false;
      } else if (ch === '"') inStr = true;
      else if (ch === '{') depth++;
      else if (ch === '}' && --depth === 0) {
        end = i;
        break;
      }
    }
    if (end === -1) return null; // unbalanced (e.g. truncated output)
    try {
      const obj = JSON.parse(text.slice(start, end + 1));
      if (isPlainObject(obj)) return obj;
    } catch {
      /* try the next '{' */
    }
    from = start + 1;
  }
  return null;
}

/** Some models wrap the object as { analyses: [...] } / { analysis: {...} } / { TICKER: {...} }. */
function unwrap(obj, ticker) {
  if (!isPlainObject(obj)) return null;
  if (typeof obj.executiveSummary === 'string') return obj;
  const candidates = [obj.analysis, obj[ticker], obj.analyses];
  for (const c of candidates) {
    if (Array.isArray(c) && isPlainObject(c[0])) return c[0];
    if (isPlainObject(c)) return isPlainObject(c[ticker]) ? c[ticker] : c;
  }
  return obj;
}

// ---------- request validation ----------

/** Returns { rows, lang, liveFeedUpdatedAtUTC } or { error }. */
export function validateBody(body) {
  if (!isPlainObject(body)) return { error: 'Body must be a JSON object' };
  if (!Array.isArray(body.rows) || body.rows.length < 1 || body.rows.length > MAX_ROWS) {
    return { error: `rows must be an array of 1..${MAX_ROWS} items` };
  }
  let lang = 'ar';
  if (body.lang !== undefined && body.lang !== null) {
    if (body.lang !== 'ar' && body.lang !== 'en') return { error: "lang must be 'ar' or 'en'" };
    lang = body.lang;
  }
  const rows = [];
  const seen = new Set();
  for (let i = 0; i < body.rows.length; i++) {
    const r = body.rows[i];
    if (!isPlainObject(r)) return { error: `rows[${i}] must be an object` };
    const ticker = typeof r.ticker === 'string' ? r.ticker.trim().toUpperCase() : '';
    if (!TICKER_RE.test(ticker)) return { error: `rows[${i}].ticker is invalid` };
    if (seen.has(ticker)) continue; // same de-duplication as the existing workflow
    seen.add(ticker);
    const row = { ticker };
    for (const f of LABEL_FIELDS) row[f] = toLabel(r[f]);
    for (const f of NUMERIC_FIELDS) row[f] = toNum(r[f]);
    for (const f of FLEX_FIELDS) {
      const v = r[f];
      row[f] = typeof v === 'boolean' ? v : toNum(v) ?? toLabel(v);
    }
    row.quoteTime = toLabel(r.quoteTime ?? r.timestampET, 40);
    rows.push(row);
  }
  const live = body.liveFeedUpdatedAtUTC;
  const liveFeedUpdatedAtUTC = typeof live === 'string' && live.trim() ? live.trim().slice(0, 64) : null;
  return { rows, lang, liveFeedUpdatedAtUTC };
}

// ---------- research + prompt ----------

function normaliseNews(items, limit) {
  const out = [];
  for (const it of Array.isArray(items) ? items : []) {
    if (!isPlainObject(it)) continue;
    const title = cleanText(it.title, 200);
    const url = httpUrl(it.url);
    if (!title || !url) continue;
    out.push({ title, url, publisher: cleanText(it.publisher, 80), date: isoDay(it.date) });
    if (out.length >= limit) break;
  }
  return out;
}

function normaliseFilings(items, limit) {
  const out = [];
  for (const it of Array.isArray(items) ? items : []) {
    if (!isPlainObject(it)) continue;
    const form = cleanText(it.form, 20);
    const url = httpUrl(it.url);
    const title = cleanText(it.title, 200) || form;
    if (!title || !url) continue;
    out.push({ form, title, url, date: isoDay(it.date) });
    if (out.length >= limit) break;
  }
  return out;
}

/** Sources come ONLY from the research items we supplied to the model. */
export function buildSources(news, filings) {
  const filingSlots = Math.min(filings.length, 2);
  const picked = news.slice(0, MAX_SOURCES - filingSlots).map((n) => ({
    title: n.title, url: n.url, publisher: n.publisher, date: n.date,
  }));
  for (const f of filings) {
    if (picked.length >= MAX_SOURCES) break;
    picked.push({
      title: f.form && !f.title.startsWith(f.form) ? `${f.form}: ${f.title}` : f.title,
      url: f.url, publisher: 'SEC EDGAR', date: f.date,
    });
  }
  return picked;
}

export function buildMessages(row, news, filings, lang) {
  const t = TEXT[lang] || TEXT.ar;
  const metrics = {};
  for (const [k, v] of Object.entries(row)) {
    if (k !== 'ticker' && v !== null && v !== undefined) metrics[k] = v;
  }
  const newsLines = news.length
    ? news.map((n, i) => `${i + 1}. [${n.date || '?'}] ${n.title}${n.publisher ? ' — ' + n.publisher : ''}`).join('\n')
    : t.none;
  const filingLines = filings.length
    ? filings.map((f, i) => `${i + 1}. [${f.date || '?'}] ${f.form ? f.form + ' — ' : ''}${f.title}`).join('\n')
    : t.none;
  const user = [
    `${t.ticker}: ${row.ticker}`,
    `${t.metrics}: ${JSON.stringify(metrics)}`,
    `${t.news}:\n${newsLines}`,
    `${t.filings}:\n${filingLines}`,
    `${t.ask}\n${SKELETON}`,
  ].join('\n\n');
  return [
    { role: 'system', content: t.system },
    { role: 'user', content: user },
  ];
}

// ---------- analysis objects ----------

function v6News(news) {
  return news.slice(0, 5).map((n) => ({ title: n.title, link: n.url, publisher: n.publisher, date: n.date }));
}

/** Repair model output into the strict analysis shape. Returns null if unusable. */
export function repairAnalysis(raw, { ticker, lang, news, filings, model, nowIso }) {
  const obj = unwrap(raw, ticker);
  if (!obj) return null;
  const executiveSummary = cleanText(obj.executiveSummary);
  if (!executiveSummary) return null; // an empty shell is not an analysis
  const t = TEXT[lang] || TEXT.ar;
  let confidence = cleanConfidence(obj.confidence);
  let latestNewsTake = cleanText(obj.latestNewsTake);
  if (news.length === 0) {
    if (filings.length === 0) confidence = Math.min(confidence, 35);
    latestNewsTake = cleanText(latestNewsTake ? `${latestNewsTake} ${t.noNews}` : t.noNews, MAX_TEXT + t.noNews.length + 1);
  }
  const a = {
    ticker,
    company: cleanText(obj.company, 120),
    asOf: nowIso,
    executiveSummary,
    shortTermSetup: cleanText(obj.shortTermSetup),
    liquidityRead: cleanText(obj.liquidityRead),
    technicalRead: cleanText(obj.technicalRead),
    fundamentalGrowth: cleanText(obj.fundamentalGrowth),
    catalysts: cleanList(obj.catalysts),
    risks: cleanList(obj.risks),
    dilutionAndFinancing: cleanText(obj.dilutionAndFinancing),
    latestNewsTake,
    confidence,
    verdict: cleanVerdict(obj.verdict),
    sources: buildSources(news, filings),
    aiStatus: 'OK',
    mode: PROVIDER,
    model,
    generatedAtUTC: nowIso,
  };
  return withV6Aliases(a, news);
}

function failedAnalysis({ ticker, lang, news = [], filings = [], model, nowIso, reason }) {
  const t = TEXT[lang] || TEXT.ar;
  const a = {
    ticker,
    company: '',
    asOf: nowIso,
    executiveSummary: t.failed(ticker),
    shortTermSetup: '',
    liquidityRead: '',
    technicalRead: '',
    fundamentalGrowth: '',
    catalysts: [],
    risks: [],
    dilutionAndFinancing: '',
    latestNewsTake: '',
    confidence: 0,
    verdict: 'INSUFFICIENT_EVIDENCE',
    sources: buildSources(news, filings),
    aiStatus: 'MODEL_FAILED',
    aiError: reason || 'model_failed',
    mode: PROVIDER,
    model,
    generatedAtUTC: nowIso,
  };
  return withV6Aliases(a, news);
}

// tagit/live-v6.js reads `summary`, `opportunity`, `growthView`, `risks[]` and `news[{title,link,publisher}]`.
// Mirror the schema-4 fields under those names so the current UI shows this output (and, on failure,
// the explicit failure statement instead of its local rules-based fallback).
function withV6Aliases(a, news) {
  a.summary = a.executiveSummary;
  a.opportunity = a.shortTermSetup;
  a.growthView = a.fundamentalGrowth;
  a.news = v6News(news);
  return a;
}

// ---------- route ----------

export function register(router, deps) {
  const { auth, limiter, llm, usage, research } = deps;
  const config = deps.config || {};
  const now = typeof deps.now === 'function' ? deps.now : Date.now;
  const cache = new Map(); // key -> { at, analysis }

  const cacheKey = (row, lang) =>
    `${row.ticker}|${row.price === null ? 'na' : Number(row.price.toPrecision(2))}|${lang}`;

  function cacheGet(key) {
    const hit = cache.get(key);
    if (!hit) return null;
    if (now() - hit.at > CACHE_TTL_MS) {
      cache.delete(key);
      return null;
    }
    return structuredClone(hit.analysis);
  }

  function cacheSet(key, analysis) {
    cache.delete(key);
    cache.set(key, { at: now(), analysis: structuredClone(analysis) });
    while (cache.size > CACHE_MAX) cache.delete(cache.keys().next().value);
  }

  function recordUsage(identity, result, messages, ms, ok) {
    try {
      const est = (text) => (usage && typeof usage.estimateTokens === 'function' ? usage.estimateTokens(text) : 0);
      usage?.record?.({
        keyId: identity.keyId,
        project: 'tagit',
        kind: 'tagit',
        model: result?.model || config.model,
        promptTokens: result?.promptTokens ?? (result ? est(messages.map((m) => m.content).join('\n')) : 0),
        completionTokens: result?.completionTokens ?? (result ? est(String(result.content ?? '')) : 0),
        ms: result?.ms ?? ms,
        ok,
      });
    } catch {
      /* usage accounting must never break the request */
    }
  }

  async function safeResearch(fn, ticker, limit) {
    try {
      return (await fn.call(research, ticker, { limit })) || [];
    } catch {
      return []; // research is contractually non-throwing; stay safe anyway
    }
  }

  /** Returns { analysis, ok, unavailable }. */
  async function analyzeTicker(row, lang, identity, signal) {
    const ticker = row.ticker;
    const news = normaliseNews(await safeResearch(research.news, ticker, 5), 5);
    const filings = normaliseFilings(await safeResearch(research.filings, ticker, 3), 3);
    const base = buildMessages(row, news, filings, lang);
    const t = TEXT[lang];
    let reason = 'invalid_json';

    for (let attempt = 0; attempt < 2; attempt++) {
      if (signal.aborted) break;
      const messages = attempt === 0 ? base : [...base, { role: 'user', content: t.retry }];
      const started = now();
      let result;
      try {
        result = await llm.chat({ messages, json: true, temperature: 0.2, maxTokens: 900, signal });
      } catch (err) {
        reason = (err && err.code) || 'llm_error';
        recordUsage(identity, null, messages, now() - started, false);
        if (FATAL_LLM_CODES.has(reason)) {
          return { ok: false, unavailable: true, reason, news, filings };
        }
        // A CPU timeout will almost certainly repeat; do not burn another full timeout window.
        if (reason === 'timeout') break;
        continue;
      }
      const model = result?.model || config.model;
      const analysis = repairAnalysis(extractJsonObject(result?.content), {
        ticker, lang, news, filings, model, nowIso: new Date(now()).toISOString(),
      });
      recordUsage(identity, result, messages, now() - started, Boolean(analysis));
      if (analysis) return { ok: true, analysis };
      reason = 'invalid_json';
    }
    return { ok: false, unavailable: false, reason, news, filings };
  }

  router.add('POST', '/api/tagit/analyze', async (ctx) => {
    const identity = auth.guard(ctx);
    if (!identity) return;

    const limit = limiter.check(identity.keyId);
    if (!limit.ok) {
      const retry = Math.max(1, Math.ceil(Number(limit.retryAfterSec) || 1));
      sendErr(ctx.res, 429, 'rate_limited', 'Too many requests', { 'Retry-After': String(retry) });
      return;
    }

    if (identity.role !== 'admin' && identity.project !== 'tagit') {
      sendErr(ctx.res, 403, 'forbidden', "This key is not scoped to project 'tagit'");
      return;
    }

    let body;
    try {
      body = await ctx.json();
    } catch (err) {
      const status = Number.isInteger(err?.status) && err.status >= 400 && err.status < 500 ? err.status : 400;
      sendErr(ctx.res, status, err?.code || 'bad_request', err?.message || 'Invalid JSON body');
      return;
    }
    const input = validateBody(body);
    if (input.error) {
      sendErr(ctx.res, 400, 'invalid_request', input.error);
      return;
    }
    const { rows, lang, liveFeedUpdatedAtUTC } = input;

    // Stop spending CPU when the caller goes away mid-run.
    const ac = new AbortController();
    const onClose = () => ac.abort();
    ctx.res?.on?.('close', onClose);

    const analyses = {};
    let okCount = 0;
    let unavailable = false;
    let model = config.model || '';
    try {
      for (const row of rows) {
        if (ac.signal.aborted) return;
        const nowIso = new Date(now()).toISOString();
        if (unavailable) {
          analyses[row.ticker] = failedAnalysis({ ticker: row.ticker, lang, model, nowIso, reason: 'model_unavailable' });
          continue;
        }
        const key = cacheKey(row, lang);
        const cached = cacheGet(key);
        if (cached) {
          analyses[row.ticker] = cached;
          okCount++;
          continue;
        }
        const r = await analyzeTicker(row, lang, identity, ac.signal);
        if (r.ok) {
          analyses[row.ticker] = r.analysis;
          model = r.analysis.model || model;
          cacheSet(key, r.analysis);
          okCount++;
        } else {
          if (r.unavailable) unavailable = true;
          analyses[row.ticker] = failedAnalysis({
            ticker: row.ticker, lang, news: r.news, filings: r.filings, model,
            nowIso: new Date(now()).toISOString(), reason: r.reason,
          });
        }
      }
    } finally {
      ctx.res?.off?.('close', onClose);
    }
    if (ac.signal.aborted) return;

    const total = Object.keys(analyses).length;
    let status = 'OK';
    if (unavailable && okCount === 0) status = 'MODEL_UNAVAILABLE';
    else if (okCount < total) status = 'PARTIAL';

    send(ctx.res, 200, {
      schemaVersion: 4,
      provider: PROVIDER,
      model,
      status,
      updatedAtUTC: new Date(now()).toISOString(),
      liveFeedUpdatedAtUTC,
      analysisCount: total,
      analyses,
      note: NOTE,
    });
  });
}
