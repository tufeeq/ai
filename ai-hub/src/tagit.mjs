//
// Free, self-hosted replacement for the paid "GPT + web search" workflow that writes
// tag/data/ai-stock-analysis.json (schemaVersion 4).
//
// Honest about limits: the self-hosted model has NO web browsing. For every ticker we
// fetch free public headlines/filings through `deps.research`, hand them to the model
// together with the live TAGit metrics, and accept ONLY a strictly repaired JSON object.
// `sources` are never taken from the model: they are rebuilt from the research items we
// supplied. When the model fails, the ticker says so plainly (aiStatus 'MODEL_FAILED');
// no rules-based text is ever presented as AI output.

